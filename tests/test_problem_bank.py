"""Every practice exercise must be solvable as written: an independent solution program,
run through the real judge, has to pass the tests generated by the reference solver."""
import pytest

from app import db
from app.judge.judge import judge_code
from app.models import Challenge, Problem
from app.problem_bank import EXTRA_PROBLEMS
from app.seed import ALL_PROBLEMS, seed_problems


@pytest.mark.parametrize("spec", EXTRA_PROBLEMS, ids=[s["title"] for s in EXTRA_PROBLEMS])
def test_solution_is_accepted(spec):
    cases = [(i, spec["solve"](i), True) for i in spec["samples"]] + \
            [(i, spec["solve"](i), False) for i in spec["hidden"]]
    result = judge_code(spec["solution"], cases, spec.get("time_limit", 2), 256)
    assert result["verdict"] == "AC", result["error"]


def test_bank_metadata_is_complete():
    titles = [s["title"] for s in ALL_PROBLEMS]
    assert len(titles) == len(set(titles)), "duplicate exercise titles"
    for spec in ALL_PROBLEMS:
        assert spec["difficulty"] in ("Easy", "Medium", "Hard"), spec["title"]
        assert spec["samples"] and spec["hidden"], spec["title"]
        assert "### Input" in spec["description"] and "### Output" in spec["description"], spec["title"]


def test_seed_is_idempotent(app):
    with app.app_context():
        before = Problem.query.count()  # conftest adds one exercise
        assert seed_problems() == len(ALL_PROBLEMS)
        assert seed_problems() == 0
        assert Problem.query.count() == before + len(ALL_PROBLEMS)
        assert Challenge.query.count() == 1
        edit = Problem.query.filter_by(title="Edit Distance").one()
        assert edit.time_limit == 3 and edit.status == "approved"
